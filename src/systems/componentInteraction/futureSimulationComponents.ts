import type { LanguageCode } from '../../types/physics';
import type {
  ComponentExplanationContent,
  RegisteredSimulationComponent,
  SimulationComponentRegistryEntry,
} from './types';

function createFutureComponent(
  simulationId: RegisteredSimulationComponent['simulationId'],
  id: string,
  names: Record<LanguageCode, string>,
  ident: Record<LanguageCode, string>,
  definition: string,
  characteristics: string,
  fnDesc: string,
  props: string,
  behaviour: string,
  rel: string,
  example: string,
  whyItMatters?: string
): RegisteredSimulationComponent {
  return {
    id,
    simulationId,
    iconKey: 'generic',
    displayName: names,
    identificationText: ident,
    hitRegion: { kind: 'svg_element', selector: `[data-component-id="${id}"]` },
    highlight: {
      strokeColor: '#6F4E37',
      glowColor: 'rgba(111, 78, 55, 0.25)',
      strokeWidth: 3,
      emissiveHex: 0x6f4e37,
      emissiveIntensity: 0.45,
    },
    explanationContext: `${names.en}: ${definition} ${props}`,
    describeCurrentState: (_lang, state) =>
      typeof state.summary === 'string' ? state.summary : ident.en,
    buildDefaultExplanation: (lang): ComponentExplanationContent => ({
      name: names[lang] || names.en,
      definition,
      characteristics,
      functionDescription: fnDesc,
      scientificProperties: props,
      behaviour,
      relationshipWithOthers: rel,
      realWorldExample: example,
      whyItMatters:
        whyItMatters ||
        `Understanding ${names.en.toLowerCase()} helps connect textbook physics equations directly to how this real-world system behaves.`,
      source: 'curated',
    }),
  };
}

